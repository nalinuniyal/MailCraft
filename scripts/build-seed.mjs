// Generates supabase/seed.sql from scripts/seed/*.mjs. Idempotent: rows have
// deterministic ids and are upserted, so re-running the seed updates them.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { CATEGORIES, TEMPLATES } from "./seed/templates.mjs";
import { COMPONENTS } from "./seed/components.mjs";

const TAG = "$mc$";

const uuid = (ns, slug) => {
  const h = createHash("sha1").update(`mailcraft:${ns}:${slug}`).digest("hex");
  const variant = ((parseInt(h[16], 16) & 3) | 8).toString(16);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${variant}${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const dq = (s) => {
  if (s.includes(TAG)) throw new Error(`content contains ${TAG}`);
  return TAG + s + TAG;
};
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;

const out = [
  "-- Generated by scripts/build-seed.mjs. Do not edit by hand: change scripts/seed/*.mjs and run `npm run seed:build`.",
  "-- Built-in categories, demo templates and components (user_id NULL, is_system true). Safe to run more than once.",
  "begin;",
  "",
];
for (const c of CATEGORIES) {
  out.push(`insert into public.template_categories (id, slug, name, description, sort_order) values ('${uuid("cat", c.slug)}', ${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${c.sort_order})
  on conflict (slug) do update set name = excluded.name, description = excluded.description, sort_order = excluded.sort_order;`);
}
out.push("");
for (const t of TEMPLATES) {
  if (!CATEGORIES.some((c) => c.slug === t.category)) throw new Error(`unknown category ${t.category}`);
  out.push(`insert into public.email_templates (id, user_id, category_id, name, description, html, tags, is_system)
  values ('${uuid("tpl", t.slug)}', null, (select id from public.template_categories where slug = ${q(t.category)}), ${q(t.name)}, ${q(t.description)}, ${dq(t.html)}, ${arr(t.tags)}, true)
  on conflict (id) do update set category_id = excluded.category_id, name = excluded.name, description = excluded.description, html = excluded.html, tags = excluded.tags;`);
}
out.push("");
for (const c of COMPONENTS) {
  out.push(`insert into public.saved_components (id, user_id, kind, name, description, html, tags, is_system)
  values ('${uuid("cmp", c.slug)}', null, ${q(c.kind)}, ${q(c.name)}, ${q(c.description)}, ${dq(c.html)}, ${arr(c.tags)}, true)
  on conflict (id) do update set kind = excluded.kind, name = excluded.name, description = excluded.description, html = excluded.html, tags = excluded.tags;`);
}
out.push("", "commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`seed.sql: ${CATEGORIES.length} categories, ${TEMPLATES.length} templates, ${COMPONENTS.length} components`);
